"""Stage 0 (context codebook) checks, experiments/s0_codebook.py.
1. Direct vs flip: next = D(key) = centre XOR G(key) on every key, for random tables (m0 and m1 sizes).
2. Metric correctness: change precision/recall/F1 on a hand example; an all-HOLD table gives one-step error = hold
   error, change F1 = 0, and a constant rollout.
3. Rule assignment: windows generated by two known rules (shift east, 4-neighbour erosion) on random blobs are split
   exactly by hard-EM with K = 2, with zero loss, and each learned table reproduces its generator on the seen keys.
4. Determinism: the same seed gives identical codebooks and assignments.
5. Frozen codebook: evaluation does not modify the tables.
6. No future leakage: observation-only, kNN and prior codes are unchanged when every frame after s is scrambled.
7. Reproduction: tie='zero' per-window m0 tables reproduce FINDINGS §10a (lut.jsonl, R1) transfer errors exactly.
8. Split manifest: no pool tile (with its prefix) touches an eval window (with its prefix, +-margin) or a val/test scene."""
import copy, json, os, sys
import numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path[:0] = [ROOT, os.path.join(ROOT, "experiments")]
import s0_codebook as s0

rng = np.random.default_rng(0)
# 1. direct vs flip
for nb in (9, 18):
    T = rng.integers(0, 3, 2 ** nb).astype(np.int8); k = np.arange(2 ** nb)
    assert (s0.predict(T, k) == s0.to_direct(T)).all() and (s0.to_direct(T) == (s0.centre(k) ^ s0.to_flip(T))).all()

# 2. metrics
cur = np.array([[0, 0, 1, 1]]); y = np.array([[0, 1, 1, 0]]); pred = np.array([[1, 1, 1, 1]])
m = s0.change_prf(pred, cur, y); assert (m["prec"], m["rec"]) == (0.5, 0.5) and m["f1"] == 0.5
V = (rng.random((20, 36, 48)) < 0.3).astype(np.uint8); hold = np.full((1, 512), s0.HOLD, np.int8)
p, _ = s0.onestep(hold, V, 3, "m0"); mo = s0.m_onestep(p, V, 3); assert mo["err"] == mo["hold"] > 0 and mo["f1"] == 0.0
B = s0.roll(hold, V[2], V[3], 5, "m0"); assert (B == V[3]).all()


# 3. assignment correctness on known generators
def blobs(n):
    f = (rng.random((n, 36, 48)) < 0.08).astype(np.uint8)
    for _ in range(2): f = (s0.nb(f).sum(-1) >= 2).astype(np.uint8)
    return f
def gen(rule, f0, T=17):
    out = [f0]
    for _ in range(T - 1):
        P = s0.nb(out[-1]); out.append((P[..., 3] if rule == "east" else P[..., 1] & P[..., 3] & P[..., 4] & P[..., 5] & P[..., 7]).astype(np.uint8))
    return np.stack(out)
seqs = [gen("east", f) for f in blobs(6)] + [gen("erode", f) for f in blobs(6)]
cs = [s0.counts(*s0.window_xy(S, 1, "m0")) for S in seqs]
Ts, a, loss, _ = s0.hard_em(cs, 2, 9, seed=0)
assert loss == 0 and len(set(a[:6])) == 1 and len(set(a[6:])) == 1 and a[0] != a[6], (loss, a)
for i, c in enumerate(cs): assert s0.losses(Ts[a[i]][None], c)[0] == 0      # each table reproduces its generator on seen keys

# 4. determinism
Ts2, a2, l2, _ = s0.hard_em(cs, 2, 9, seed=0); assert (Ts2 == Ts).all() and (a2 == a).all() and l2 == loss

# 5. + 6. frozen codebook and no future leakage, through the real eval_window
Vs = np.concatenate([seqs[0], seqs[6], seqs[1]]); s = 20                        # window [20, 36)
books = {2: Ts.copy()}; before = copy.deepcopy(books)
pri = {2: [0, 1]}; knn = {2: lambda x: int(x[3] > x[4])}
e = dict(start=s, end=s + s0.L)
r1 = s0.eval_window(e, Vs, books, "m0", pri, knn)
assert all((books[k] == before[k]).all() for k in books)
Vf = Vs.copy(); Vf[s + 1:] = rng.integers(0, 2, Vf[s + 1:].shape)
r2 = s0.eval_window(e, Vf, books, "m0", pri, knn)
for nm in ("obs", "knn", "prior"): assert r1["K2"][nm]["code"] == r2["K2"][nm]["code"], nm
assert r1["shift_obs"]["d"] == r2["shift_obs"]["d"]

# 7. reproduction of FINDINGS §10a (R = 1)
PRE = json.load(open(os.path.join(ROOT, "runs", "readable_rules", "gen", "prereg_windows.json")))["windows"]
LUT = [json.loads(l) for l in open(os.path.join(ROOT, "runs", "readable_rules", "gen", "lut.jsonl"))]
X = s0.video()
for w, row in [(PRE[r["window"]], r) for r in LUT[:4]]:
    a_, b_ = w["train"]; T = s0.fit_table([s0.counts(*s0.window_xy(X, a_, "m0", b_ - a_ - 1))], 9, tie="zero")
    for wn in ("adjacent", "distant", "cross"):
        c_, d_ = w[wn]; k, yv = s0.window_xy(X, c_, "m0", d_ - c_ - 1)
        assert abs(float((s0.predict(T, k) != yv).mean()) - row["R1"][wn]["transfer_err"]) < 1e-12, (row["window"], wn)

# 8. manifest disjointness
man = json.load(open(s0.MAN)); forb = np.zeros(6572, bool)
for i, rl in man["scene_roles"].items():
    if rl != "fit": sc = PRE[int(i)]["scene"]; forb[sc[0]:sc[1]] = True
for ev in man["eval_windows"]: forb[ev["start"] - 3:ev["end"]] = True
for t in man["pool"]: assert not forb[t - 3:t + s0.L].any(), t
print("test_s0_codebook: all checks passed")
