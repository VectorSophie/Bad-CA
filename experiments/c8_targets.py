"""Campaign 08 structures, direct circuit simulation and positive-control clips.

STRUCT: name -> (k, hidden_seen_by, S).  base = C7 'k1_S2' (F_priv k=1, S=2); ext = 'k1s_S4' (F_shared k=1, S=4);
ablations 'k1s_S2', 'k1_S4'. Taps follow ca.rule.family_taps: visible Moore 0..8 (centre 4), then hidden
(self: 9 = own hidden; moore: 9..17, own hidden = 13).

Controls (generated by KNOWN circuits through the same simulator; only the frames are given to CGP):
  pcmove_<struct>: hidden' = NOT h (global 2-generation clock from uniform init 0); visible' = h ? W : C
                   -> every object moves right by S/2 px per frame, sustained for all 60 frames.
                   Field 24 x (12 + 60*S/2 + 6), three objects at the left.
  pccycle_<struct>: a small random circuit (<= 6 gates) chosen by a FIXED screening procedure (rng 2026,
                   first that qualifies): late-segment replay periodic with period 2..8 frames, 2-30% of
                   pixels change per frame, and not a global inversion (P_t != NOT P_{t-1} on > 50% of pixels).
Neither control can be passed by hold, all-black/white, or global inversion.
"""
import numpy as np
from ca.rule import family_taps

STRUCT = {"k1_S2": (1, "self", 2), "k1s_S4": (1, "moore", 4), "k1s_S2": (1, "moore", 2), "k1_S4": (1, "self", 4)}


def taps_of(st):
    k, seen, S = STRUCT[st]; return family_taps(k, seen)


def simulate(gates, outs, st, f0, T):
    """Binary autonomous rollout of a circuit (pool = taps + gates) from visible f0, hidden 0, boundary 0.
    Only gates reachable from outputs are evaluated. Returns observed visible frames (T,H,W) uint8."""
    k, seen, S = STRUCT[st]; taps = family_taps(k, seen); n = len(taps); C = k + 1
    need = set(); stack = [o for o in outs if o >= n]
    while stack:
        p = stack.pop()
        if p in need: continue
        need.add(p); _, a, b = gates[p - n]; stack += [x for x in (a, b) if x >= n]
    order = sorted(need)
    H, W = f0.shape; s = np.zeros((C, H, W), np.uint8); s[0] = f0; out = [f0.copy()]
    for _ in range(1, T):
        for _ in range(S):
            pd = np.pad(s, ((0, 0), (1, 1), (1, 1)))
            pool = {i: pd[c, 1 + dy:1 + dy + H, 1 + dx:1 + dx + W] for i, (c, dy, dx) in enumerate(taps)}
            for p in order:
                tt, a, b = gates[p - n]
                pool[p] = (tt >> (pool[a] * 2 + pool[b])) & 1
            s = np.stack([pool[o].astype(np.uint8) for o in outs])
        out.append(s[0].copy())
    return np.stack(out)


def _pcmove(st):
    k, seen, S = STRUCT[st]; n = len(taps_of(st)); h = 9 if seen == "self" else 13
    # g0 = NOT h (tt 5 = NOT b on (x0, h)); g1 = W AND h; g2 = C AND NOT h; g3 = g1 OR g2; outputs: visible g3, hidden g0
    gates = [(5, 0, h), (8, 3, h), (4, 4, h), (14, n + 1, n + 2)]
    return gates, [n + 3, n]


def control(name, T=60):
    kind, st = name.split("_", 1)
    if kind == "pcmove":
        S = STRUCT[st][2]; Wd = 12 + 60 * S // 2 + 6; f0 = np.zeros((24, Wd), np.uint8)
        f0[3:9, 2:8] = 1; f0[11:14, 1:10] = 1; f0[16:22, 3:6] = 1; f0[18:20, 6:9] = 1
        g, o = _pcmove(st); return simulate(g, o, st, f0, T), (g, o)
    if kind == "pccycle":
        rng = np.random.default_rng(2026); n = len(taps_of(st))
        f0 = (np.random.default_rng(7).random((24, 24)) < 0.35).astype(np.uint8)
        for _ in range(20000):
            G = int(rng.integers(2, 7))
            g = [(int(rng.integers(16)), *sorted(int(x) for x in rng.choice(n + j, 2, replace=False))) for j in range(G)]
            o = [n + G - 1, int(rng.integers(n + G))]
            P = simulate(g, o, st, f0, T)
            late = range(40, T); ch = (P[1:] != P[:-1]).mean((1, 2))[39:]
            per = next((p for p in range(1, 9) if all((P[t] == P[t - p]).all() for t in late)), None)
            inv = np.mean([(P[t] == 1 - P[t - 1]).mean() for t in late])
            if per and 2 <= per <= 8 and 0.02 <= ch.min() and ch.max() <= 0.30 and inv < 0.5:
                return P, (g, o)
        raise RuntimeError("no qualifying cycle circuit")
    raise KeyError(name)
